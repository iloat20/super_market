import '../../config/app_config.dart';

/// 「按关键词搜股票」的能力（与「下载全量目录」是两件事）。
///
/// ## 为什么需要它
///
/// 换股票原来的做法是：先把全市场 5577 条目录拉下来，再在本地做字符串匹配。
/// 实测拉一次要 **68.6 秒**（56 页串行 + 每页之间空等 400ms），而用户真正
/// 想做的只是「输入两个字，选中一只」——为了匹配一次字符串，先下载 5223 条
/// 记录，这是典型的把手段当成了目的。
///
/// 搜索建议接口是另一条路：**输入什么就问什么，一次 170–380ms、131 字节**。
///
/// ## 为什么这个协议只有三个方法
///
/// 与 [SymbolCatalog] 刻意分开：
///
/// | | 目录 | 搜索 |
/// | --- | --- | --- |
/// | 触发时机 | 后台预热（3.8s，用户看不见） | 每次输入（250ms 防抖） |
/// | 失败影响 | 只影响离线搜索 | 必须让用户知道「这次没搜到」 |
/// | 数据量 | 5577 条 | 最多 50 条 |
///
/// 混成一个接口会让「目录下载失败」和「搜索没结果」的语义搅在一起，
/// 而这两件事的恢复手段完全不同（前者重试/等后台，后者换个词）。
abstract interface class SymbolSearch {
  /// 唯一标识（日志 tag、将来做多源轮换用）
  String get id;

  /// 界面展示用的来源名
  String get displayName;

  /// 关键词 → 请求地址
  Uri suggestUri(String query);

  /// 请求头（这类接口普遍校验 Referer）
  Map<String, String> get requestHeaders;

  /// 原始字节 → 候选股票。
  ///
  /// **收 `List<int>` 而不是 String**：字符集是协议细节。腾讯这套是纯 ASCII
  /// （中文写成 `\u8d35` 这样的字面转义），新浪那套是 GBK——同一个类型签名下，
  /// 「怎么解字节」应该由知道协议的那一层决定，不能在上游就 `utf8.decode` 掉。
  ///
  /// 解析不出东西时返回空列表，**不抛异常**：搜索是高频交互，
  /// 服务端偶尔返回 `v_hint="N"`（无结果）或一段 HTML 都很正常，
  /// 让调用方去 try/catch 只会把「没搜到」和「网络坏了」混为一谈。
  List<StockConfig> parse(List<int> bytes);
}
