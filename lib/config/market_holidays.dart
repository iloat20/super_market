  /// 表覆盖到的最后一年。
  ///
  /// 加完新一年的数据必须同步改这里：`market_holidays_test.dart` 有一条
  /// 「日历还没过期」的断言，跨年即红，免得这处静默退回「节假日显示交易中」。
  static const int lastCoveredYear = 2027;

  /// `DateTime` → 表键（`20260217`）。只看年月日，时分秒一律丢掉。
  static int keyOf(DateTime day) =>
      day.year * 10000 + day.month * 100 + day.day;

  /// [day] 在 [region] 市场是否全天休市。
  ///
  /// `region` 取 `SH` / `SZ` / `HK` / `US`；空串或未知值按 A 股处理。
  static bool isClosedOn(DateTime day, String region) =>
      byRegion[_bucket(region)]?.contains(keyOf(day)) ?? false;

  /// [day] 在 [region] 市场是否半日市（只有早市）。
  static bool isHalfDayOn(DateTime day, String region) =>
      halfDays[_bucket(region)]?.contains(keyOf(day)) ?? false;

  /// 市场代码 → 表分组。沪深共用 `A`，未知值也落 `A`。
  static String _bucket(String region) => switch (region) {
    'HK' => 'HK',
    'US' => 'US',
    _ => 'A',
  };
}
