  ///
  /// 这张表只回答「哪一天」，收盘时刻由 `MarketSession` 按市场给常量
  /// （港股含收市竞价到 12:10，美股 13:00 ET）——两地各自的规则都是固定的，
  /// 没必要在数据里重复一遍。
  static const Map<String, Set<int>> halfDays = <String, Set<int>>{
    'HK': <int>{
