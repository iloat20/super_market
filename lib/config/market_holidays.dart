/// 交易所休市日历（纯数据：零 I/O、零外部接口）。
///
/// 为什么要有它：`MarketSession` 原先只判「工作日 + 时段」，于是春节、国庆
/// 这类**工作日但交易所休市**的日子会显示成「交易中」——用户打开 App 第一眼
/// 看到的就是错话。交易日历算不出来（A 股调休由国务院逐年拍板、港股佛诞跟
/// 农历），只能抄表；一张表 80 来条，每年补一次。
///
/// 数据来源（2026-11-07 抄录，改表前先对一遍原文）：
///
/// | 市场 | 依据 |
/// | --- | --- |
/// | A 股 | 上证公告〔2025〕45 号《关于上海证券交易所 2026 年部分节假日休市安排的通知》 |
/// | A 股 2027 | 国办发明电〔2026〕10 号放假安排推导；交易所正式通知一般 12 月发布，届时应复核 |
/// | 港股 | 港交所《2026 年香港证券市场假期》通告（cc_SEHK_CT_075_2025）及 2027 年假期表 |
/// | 美股 | NYSE《Holidays & Trading Hours》2026 / 2027 |
///
/// 三条编码决定，都是踩过坑才这么定的：
///
/// 1. **键是 `20260217` 这样的整数，不是 `DateTime`**。`DateTime` 没有 const
///    构造器，装不进 const 表；更麻烦的是它带时分秒——`DateTime(2026,2,17,9)`
///    与 `DateTime(2026,2,17)` 并不相等，拿带时刻的 `DateTime` 直接查表会
///    **静默漏掉**。整数键只看年月日，把这类错误从「运行时偶发」变成「不会发生」。
/// 2. **只收周一到周五**。周末在 `MarketSession` 里先判掉；表里塞周末既没用，
///    又给「抄错一天」多开一扇门。`market_holidays_test.dart` 有一条不变量守它。
/// 3. **A 股一张表覆盖 SH/SZ**。沪深两市休市安排逐字相同，分两处存只会让两份
///    数据各自漂移。`isClosedOn(day, 'SH')` 与 `'SZ'` 查的是同一份；未知市场
///    （老报文没有 `r` 字段）也落回这张表，与 `tradingDayOf` 的口径一致。
///
/// 维护：加完新一年的数据，**必须**同步改 [lastCoveredYear]。有一条测试会在
/// 过期后变红——那是提醒，不是误报。
